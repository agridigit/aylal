"""Registry export jobs: request (limits, one active job per farm, 10 per hour) and status.

The job row holds the file keys, generated by the server only (`farms/{farm_id}/exports/{job_id}/...`); they are
never read from a client body nor returned. Building the files is the worker's job.
"""
import datetime as dt
import re
import uuid
from typing import Any

from fastapi import HTTPException
from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

from app.domain.operation_limits import LIMITS
from app.operations.service import OperationError, lock_farm
from app.operations.storage import ObjectStorage

_PER_HOUR = 10


def _plus_years(day: dt.date, years: int) -> dt.date:
    try:
        return day.replace(year=day.year + years)
    except ValueError:  # 29 February
        return day.replace(year=day.year + years, day=28)


async def request_export(
    session: AsyncSession, farm_id: uuid.UUID, user_id: uuid.UUID, body: dict[str, Any], *, lang_default: str = "fr"
) -> dict[str, Any]:
    start, end = body["period_from"], body["period_to"]
    if end < start or end > _plus_years(start, LIMITS["export_years"]):
        raise OperationError(422, "validation", "period_to")
    if body["scope"] == "parcel":
        found = body.get("parcel_id") and (
            await session.execute(
                text("SELECT 1 FROM parcels WHERE id = :p AND farm_id = :f"), {"p": body["parcel_id"], "f": farm_id}
            )
        ).first()
        if not found:
            raise OperationError(404, "not_found")
    await lock_farm(session, farm_id)
    active = (
        await session.execute(
            text("SELECT 1 FROM export_jobs WHERE farm_id = :f AND state IN ('queued', 'running')"), {"f": farm_id}
        )
    ).first()
    if active:
        raise HTTPException(status_code=409, detail={"code": "export_already_active"})
    recent = (
        await session.execute(
            text("SELECT count(*) FROM export_jobs WHERE farm_id = :f AND created_at > now() - interval '1 hour'"),
            {"f": farm_id},
        )
    ).scalar_one()
    if recent >= _PER_HOUR:
        raise HTTPException(status_code=429, detail={"code": "rate_limited"}, headers={"Retry-After": "3600"})
    rows = (
        await session.execute(
            text(
                "SELECT count(*) FROM registry_current WHERE farm_id = :f AND performed_on BETWEEN :a AND :b"
                " AND (CAST(:p AS uuid) IS NULL OR parcel_id = CAST(:p AS uuid))"
            ),
            {"f": farm_id, "a": start, "b": end, "p": body.get("parcel_id") if body["scope"] == "parcel" else None},
        )
    ).scalar_one()
    if rows > LIMITS["export_rows"]:
        raise OperationError(422, "export_too_large", "period_to")
    job_id = uuid.uuid4()
    await session.execute(
        text(
            "INSERT INTO export_jobs (id, farm_id, requested_by, scope, parcel_id, period_from, period_to, format, lang,"
            " state, row_count) VALUES (:i, :f, :u, :scope, :p, :a, :b, :fmt, :lang, 'queued', :n)"
        ),
        {"i": job_id, "f": farm_id, "u": user_id, "scope": body["scope"], "p": body.get("parcel_id"), "a": start, "b": end,
         "fmt": body["format"], "lang": body.get("lang") or lang_default, "n": rows},
    )
    return {"id": str(job_id), "state": "queued", "row_count": rows}


_URL_SECONDS = 900


async def job_status(
    session: AsyncSession, farm_id: uuid.UUID, job_id: uuid.UUID, user_id: uuid.UUID, storage: ObjectStorage
) -> dict[str, Any]:
    """Job state. Signed download URLs (15 min at most) are issued to the requester only, for the server's own keys
    of this job; anyone else gets the 404 of an unknown job, an expired job a 410, and no object key is ever returned."""
    row = (
        await session.execute(
            text(
                "SELECT id, scope, parcel_id, period_from, period_to, format, lang, state, sha256, row_count, expires_at,"
                " created_at, file_keys FROM export_jobs WHERE id = :i AND farm_id = :f AND requested_by = :u"
            ),
            {"i": job_id, "f": farm_id, "u": user_id},
        )
    ).mappings().first()
    if row is None:
        raise OperationError(404, "not_found")
    keys = row["file_keys"]
    out: dict[str, Any] = {
        k: (v.isoformat() if isinstance(v, (dt.date, dt.datetime)) else str(v) if isinstance(v, uuid.UUID) else v)
        for k, v in row.items() if k != "file_keys"
    }
    out["downloads"] = {}
    if row["state"] != "done":
        return out
    if row["expires_at"] is not None and row["expires_at"] <= dt.datetime.now(dt.UTC):
        raise HTTPException(status_code=410, detail={"code": "export_expired"})
    allowed = re.compile(rf"farms/{farm_id}/exports/{job_id}/[A-Za-z0-9._-]+")
    for fmt, key in (keys or {}).items():
        if fmt not in ("pdf", "xlsx") or not isinstance(key, str) or not allowed.fullmatch(key):
            raise OperationError(404, "not_found")  # a key outside the job's own prefix is never signed
        out["downloads"][fmt] = storage.presign_get(key, _URL_SECONDS)
    return out


async def registry_export_for_deletion(session: AsyncSession, user_id: uuid.UUID) -> list[str]:
    """Before an account that owns farms with registry entries is anonymised, queue a full export for the requester.

    Returns the job ids (an already active job of the farm is reused). The registry itself is kept.
    """
    farms = (
        await session.execute(
            text(
                "SELECT m.farm_id FROM farm_members m JOIN farms f ON f.id = m.farm_id AND f.deleted_at IS NULL"
                " WHERE m.user_id = :u AND m.role = 'owner' AND m.removed_at IS NULL"
                " AND EXISTS (SELECT 1 FROM registry_entries r WHERE r.farm_id = m.farm_id) ORDER BY m.farm_id"
            ),
            {"u": user_id},
        )
    ).scalars().all()
    ids: list[str] = []
    for farm_id in farms:
        await lock_farm(session, farm_id)
        active = (
            await session.execute(
                text("SELECT id FROM export_jobs WHERE farm_id = :f AND state IN ('queued', 'running')"), {"f": farm_id}
            )
        ).scalar()
        if active is not None:
            ids.append(str(active))
            continue
        job_id = uuid.uuid4()
        await session.execute(
            text(
                "INSERT INTO export_jobs (id, farm_id, requested_by, scope, period_from, period_to, format, lang, state, row_count)"
                " SELECT CAST(:i AS uuid), CAST(:f AS uuid), CAST(:u AS uuid), 'farm', min(r.performed_on), max(r.performed_on), 'both',"
                " COALESCE((SELECT language FROM users WHERE id = :u), 'fr'), 'queued', count(*)"
                " FROM registry_entries r WHERE r.farm_id = :f"
            ),
            {"i": job_id, "f": farm_id, "u": user_id},
        )
        ids.append(str(job_id))
    return ids
